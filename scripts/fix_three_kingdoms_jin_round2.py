def dyn_from_nianhao(text: str) -> str | None:
    """通過年號判斷西晉/東晉/三國（僅用唯一不歧義的年號）"""
    for nh, dyn in UNIQUE_NIANHAO.items():
        if dyn and nh in text:
            return dyn
    return None


def dyn_from_cbdb_text(text: str) -> tuple[str | None, str | None]:
    """從 cbdb_source 文本提取顯式朝代詞 或 生卒年"""
    # 1. 顯式朝代詞
    if "東晉" in text or "東晋" in text:
        return "東晉", "cbdb_source:explicit:東晉"
    if "西晉" in text or "西晋" in text:
        return "西晉", "cbdb_source:explicit:西晉"
    if "曹魏" in text or "三國魏" in text:
        return "三國魏", "cbdb_source:explicit:三國魏"
    if "孫吳" in text or "三國吳" in text or "吳人" in text:
        return "三國吳", "cbdb_source:explicit:三國吳"
    if "蜀漢" in text or "三國蜀" in text:
        return "三國蜀", "cbdb_source:explicit:三國蜀"
    if "三國" in text and "西晉" not in text and "東晉" not in text:
        # 提到三國但未更細分
        pass

    # 2. 生卒年 -> 用卒年所在時段判斷
    years = re.findall(r'(\d{3,4})[?-]?(\d{3,4})?', text)
    # 只取合理的生卒年（100-500之間）
    valid_years = []
    for by, dy in years:
        try:
            bi = int(by); di = int(dy) if dy else None
            if 100 <= bi <= 500:
                valid_years.append(('birth', bi))
            if di and 100 <= di <= 500:
                valid_years.append(('death', di))
        except: pass

    # 取最靠后的年份判斷
    if valid_years:
        # 按年份排序
        valid_years.sort(key=lambda x: x[1])
        last_ty, last_y = valid_years[-1]
        if last_y <= 280:
            if last_y <= 265:
                # 大概率三國，需要更細信息
                pass
            else:
                return "西晉", f"cbdb_source:卒年{last_y}→西晉"
        elif 265 < last_y <= 316:
            return "西晉", f"cbdb_source:卒年{last_y}→西晉"
        elif 317 <= last_y <= 420:
            return "東晉", f"cbdb_source:卒年{last_y}→東晉"

    return None, None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--commit", action="store_true")
    args = ap.parse_args()
    commit = args.commit or not args.dry_run

    stats = Counter()

    print("載入 Work / Entity ...")
    works = {}
    work_paths = {}
    for fp in iter_work_files():
        d = json.loads(fp.read_text(encoding="utf-8"))
        wid = d.get("id", fp.stem)
        works[wid] = d
        work_paths[wid] = fp

    entities = {}
    entity_paths = {}
    for fp in iter_entity_files():
        try:
            d = json.loads(fp.read_text(encoding="utf-8"))
        except Exception:
            continue
        eid = d.get("id", fp.stem)
        entities[eid] = d
        entity_paths[eid] = fp

    print(f"  Work: {len(works)}, Entity: {len(entities)}")

    # ========== Batch A: Entity cbdb_source ==========
    print("\n=== Batch A: Entity cbdb_source ===")
    for eid, e in entities.items():
        dyn = e.get("dynasty")
        if dyn not in ("晉", "魏", "吳", "三國"):
            continue
        ext = e.get("external_ids", {}) or {}
        cbdb_text = str(ext)
        if not cbdb_text or cbdb_text == "{}":
            continue
        new_dyn, basis = dyn_from_cbdb_text(cbdb_text)
        if new_dyn and new_dyn != dyn:
            e["dynasty"] = new_dyn
            e["dynasty_basis"] = basis
            e["updated_at"] = now_iso()
            stats[f"A.entity.{dyn}→{new_dyn}"] += 1

    # ========== Batch B: Work title 年號 ==========
    print("\n=== Batch B: Work title 年號 ===")
    for wid, w in works.items():
        title = w.get("title", "") or ""
        # 只處理 period=jin/three-kingdoms 的
        per = w.get("period")
        if per not in ("jin", "three-kingdoms"):
            continue
        new_dyn = dyn_from_nianhao(title)
        if not new_dyn:
            continue
        changed = False
        # work.top
        if w.get("dynasty") in ("晉", "魏", "吳", "三國", None):
            if w.get("dynasty") != new_dyn:
                old = w.get("dynasty")
                w["dynasty"] = new_dyn
                w["dynasty_basis"] = f"nianhao_title:{title}→{new_dyn}"
                w["updated_at"] = now_iso()
                stats[f"B.work.top.{old}→{new_dyn}"] += 1
                changed = True
        # authors
        for a in w.get("authors", []) or []:
            if isinstance(a, dict):
                adyn = a.get("dynasty")
                if adyn in ("晉", "魏", "吳", "三國") and adyn != new_dyn:
                    # 年號信號對西晉/東晉/三國 粗分有效
                    # 但三國魏/吳/蜀 不應用年號強分作者（除非 title_info 特別提到）
                    if new_dyn in ("西晉", "東晉"):
                        a["dynasty"] = new_dyn
                        a["dynasty_basis"] = f"nianhao_title:{title}→{new_dyn}"
                        stats[f"B.work.author.{adyn}→{new_dyn}"] += 1
                        changed = True

    # ========== Batch C: 擴充歷史人物詞典 ==========
    print("\n=== Batch C: 擴充歷史人物詞典 ===")
    # Entity
    for eid, e in entities.items():
        dyn = e.get("dynasty")
        if dyn not in ("晉", "魏", "吳", "三國"):
            continue
        name = e.get("primary_name", "")
        if name in EXTRA_HISTORICAL_FIGURES:
            new_dyn, note = EXTRA_HISTORICAL_FIGURES[name]
            if new_dyn != dyn:
                e["dynasty"] = new_dyn
                e["dynasty_basis"] = f"historical_dict:round2({note})"
                e["updated_at"] = now_iso()
                stats[f"C.entity.{dyn}→{new_dyn}"] += 1

    # Work.author
    for wid, w in works.items():
        w_changed = False
        for a in w.get("authors", []) or []:
            if not isinstance(a, dict):
                continue
            dyn = a.get("dynasty")
            if dyn not in ("晉", "魏", "吳", "三國"):
                continue
            name = a.get("name", "")
            if name in EXTRA_HISTORICAL_FIGURES:
                new_dyn, note = EXTRA_HISTORICAL_FIGURES[name]
                if new_dyn != dyn:
                    a["dynasty"] = new_dyn
                    a["dynasty_basis"] = f"historical_dict:round2({note})"
                    stats[f"C.author.{dyn}→{new_dyn}"] += 1
                    w_changed = True
        if w_changed:
            w["updated_at"] = now_iso()

    # ========== Batch D: 著錄志上限判斷 ==========
    # 原理：如果 Work 只被 X 志著錄（X 是唐或更後的志），不提供新信息
    # 但如果 entity.work 被《三國藝文志》單獨著錄 → 必三國
    # 反之：如果 Work 被《後漢藝文志》著錄 → 不應為西晉人作者
    # 暫略（Batch A+B+C 已涵蓋主要信號）

    # ========== Batch E: 再一輪 Entity↔Author 傳播 ==========
    print("\n=== Batch E: Entity↔Author 雙向傳播 ===")
    # Ea: Entity→Author
    entity_dyn_map = {}
    for eid, e in entities.items():
        dyn = e.get("dynasty")
        if dyn in ("三國魏", "三國蜀", "三國吳", "西晉", "東晉"):
            entity_dyn_map[eid] = dyn

    for wid, w in works.items():
        changed = False
        for a in w.get("authors", []) or []:
            if not isinstance(a, dict):
                continue
            dyn = a.get("dynasty")
            if dyn not in ("晉", "魏", "吳", "三國"):
                continue
            eid = a.get("entity_id")
            if eid and eid in entity_dyn_map:
                new_dyn = entity_dyn_map[eid]
                if new_dyn != dyn:
                    a["dynasty"] = new_dyn
                    a["dynasty_basis"] = f"entity_propagation:round2:{eid}"
                    changed = True
                    stats[f"Ea.author.{dyn}→{new_dyn}"] += 1
        if changed:
            w["updated_at"] = now_iso()

    # Eb: Author→Entity
    author_name_dyn = defaultdict(set)
    for wid, w in works.items():
        for a in w.get("authors", []) or []:
            if not isinstance(a, dict):
                continue
            dyn = a.get("dynasty")
            if dyn in ("三國魏", "三國蜀", "三國吳", "西晉", "東晉"):
                author_name_dyn[a.get("name", "")].add(dyn)

    for eid, e in entities.items():
        dyn = e.get("dynasty")
        if dyn not in ("晉", "魏", "吳", "三國"):
            continue
        name = e.get("primary_name", "")
        if name in author_name_dyn:
            classified = author_name_dyn[name]
            if len(classified) == 1:
                new_dyn = classified.pop()
                if new_dyn != dyn:
                    e["dynasty"] = new_dyn
                    e["dynasty_basis"] = "author_propagation:round2"
                    e["updated_at"] = now_iso()
                    stats[f"Eb.entity.{dyn}→{new_dyn}"] += 1

    # ========== 寫入 ==========
    if commit:
        print("\n寫入 Work ...")
        for wid, w in works.items():
            fp = work_paths[wid]
            fp.write_text(json.dumps(w, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

        print("寫入 Entity ...")
        for eid, e in entities.items():
            fp = entity_paths[eid]
            fp.write_text(json.dumps(e, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    # ========== 報告 ==========
    print("\n=== 統計 ===")
    for k, v in sorted(stats.items()):
        print(f"  {k:55s} {v:>6}")

    # 剩餘未解
    remaining = Counter()
    for e in entities.values():
        dyn = e.get("dynasty")
        if dyn in ("晉", "魏", "吳", "三國"):
            remaining[f"entity.{dyn}"] += 1
    for w in works.values():
        for a in w.get("authors", []) or []:
            if isinstance(a, dict):
                dyn = a.get("dynasty")
                if dyn in ("晉", "魏", "吳", "三國"):
                    remaining[f"author.{dyn}"] += 1
    print(f"\n=== 剩餘未解 ===")
    for k, v in sorted(remaining.items()):
        print(f"  {k:30s} {v:>6}")


if __name__ == "__main__":
    main()
