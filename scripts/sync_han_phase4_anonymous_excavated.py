def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def save(p, data, indent=2):
    with open(p, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=indent)
        f.write("\n")


def build_work_index():
    idx = {}
    for s in SHARDS:
        d = load(ROOT / "index" / "works" / f"{s}.json")
        for wid, entry in d.items():
            idx[wid] = ROOT / entry["path"]
    return idx


def main():
    widx = build_work_index()
    fixed = 0
    for wid, path in widx.items():
        try:
            j = load(path)
        except Exception:
            continue
        if j.get("period") != "qin-han":
            continue
        a = j.get("authors")
        if not a or a[0].get("name") != "佚名" or a[0].get("dynasty") != "漢":
            continue
        title = j.get("title")
        if title not in TARGETS:
            continue
        basis = TARGETS[title]
        a[0]["dynasty"] = "西漢"
        j["period_basis"] = f"據 authors[0].dynasty「西漢」（原作籠統「漢」，2026-08-11 西漢探勘分期第四階段訂正：{basis}）"
        save(path, j)
        fixed += 1
    print(f"fixed: {fixed}")


if __name__ == "__main__":
    main()
